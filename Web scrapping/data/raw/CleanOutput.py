# ============================================
# HELPERS
# ============================================
def is_empty(value):
    """Value හිස්ද check"""
    if value is None:
        return True
    if isinstance(value, str) and value.strip() == "":
        return True
    return False


def to_zero_if_empty(value):
    """හිස් නම් 0, නැත්නම් value"""
    if is_empty(value):
        return 0
    return value


def get_balanced_random_city(city_counter):
    sorted_cities = sorted(ALL_CITIES, key=lambda c: city_counter[c])
    bottom_n = max(1, len(sorted_cities) // 3)
    return random.choice(sorted_cities[:bottom_n])


# ============================================
# MAIN
# ============================================
def main():
    print("🧹 Cleaning output.csv...\n")
    print(f"📊 Cities loaded: {len(ALL_CITIES)}\n")

    rows = []
    missing_city = 0
    missing_district = 0
    zero_filled = Counter()   # ⭐ track how many zeros filled
    city_counter = Counter()

    # First pass — count existing cities
    with open(INPUT_CSV, "r", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        for row in reader:
            city = (row.get("city") or "").strip()
            if city and city in CITY_TO_DISTRICT:
                city_counter[city] += 1

    print(f"📈 Cities in data: {len(city_counter)}\n")

    # Second pass — fix
    with open(INPUT_CSV, "r", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)

        for row in reader:
            city = (row.get("city") or "").strip()
            district = (row.get("district") or "").strip()

            # ---- Fix city ----
            if not city or city not in CITY_TO_DISTRICT:
                missing_city += 1
                city = get_balanced_random_city(city_counter)
                district = CITY_TO_DISTRICT[city]
                row["city"] = city
                row["district"] = district
                city_counter[city] += 1

            # ---- Fix district ----
            elif not district:
                missing_district += 1
                district = CITY_TO_DISTRICT.get(city, "")
                row["district"] = district

            # ---- Build clean row ----
            clean_row = {}
            for col in FINAL_COLUMNS:
                value = row.get(col, "")

                # ⭐ NULL → 0 (numeric columns only)
                if col in ZERO_FILL_COLUMNS:
                    if is_empty(value):
                        clean_row[col] = 0
                        zero_filled[col] += 1
                    else:
                        clean_row[col] = value
                else:
                    # Non-numeric: keep as-is (already fixed city/district)
                    clean_row[col] = value if not is_empty(value) else ""

            rows.append(clean_row)

    # ---- Write ----
    with open(OUTPUT_CSV, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=FINAL_COLUMNS)
        writer.writeheader()
        writer.writerows(rows)

    # ---- Report ----
    print(f"{'='*60}")
    print(f"✅ DONE")
    print(f"   Total rows: {len(rows)}")
    print(f"   Missing city fixed: {missing_city}")
    print(f"   Missing district fixed: {missing_district}")
    print(f"   Cities used: {len(city_counter)}")
    print(f"   Columns: {len(FINAL_COLUMNS)}")

    if zero_filled:
        print(f"\n🔢 Null → 0 filled:")
        for col, count in zero_filled.most_common():
            print(f"   {col}: {count}")
    else:
        print(f"\n🎉 No null values found!")

    print(f"\n📊 Top 10 cities:")
    for city, count in city_counter.most_common(10):
        print(f"   {city}: {count}")

    print(f"\n📄 Output: {OUTPUT_CSV}")
    print(f"{'='*60}")


if __name__ == "__main__":
    main()